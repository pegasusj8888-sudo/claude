    if y0 <= 2018:
        out.append(seg(y0, min(y1, 2018), **F, src=ETK.format(s=s, t=F_TXT) + ', ' + TP_F + extra))
    if y1 >= 2019:
        out.append(seg(max(y0, 2019), y1, **F19, src=ETK.format(s=s, t=F_TXT) + ', ' + TP_F + extra))
    return out

